// Builds data.js (the public Georgia Southern data bundled into ROAM V14).
// Usage: node scripts/build-data.mjs <path-to-campus-roam-app/data>
// Default source: ../../roam_materials/campus-roam-app/data
// The campus-roam-app GitHub workflow refreshes that data twice a day; rerun this
// script (or point CONFIG.liveDataUrl at the hosted JSON) to pick up new events.
import fs from 'node:fs';
import path from 'node:path';

const src = process.argv[2] || path.resolve(path.dirname(new URL(import.meta.url).pathname), '../data');
const read = f => JSON.parse(fs.readFileSync(path.join(src, f), 'utf8'));

const campus = read('campus.json');
const academics = read('academics.json');
const events = read('events.json');
const orgs = read('orgs.json');
let news = { colleges: {} };
try { news = read('news.json'); } catch {}

const bundle = {
  builtAt: new Date().toISOString(),
  campus,
  academics,
  events: {
    generatedAt: events.generatedAt,
    source: events.source,
    events: (events.events || []).map(e => ({
      id: e.id, title: e.title, start: e.start, end: e.end, allDay: !!e.allDay,
      location: e.location || '', campus: e.campus || '', url: e.url || '', source: e.source,
      tags: e.tags || [], desc: e.desc || '', org: e.org || '', colleges: e.colleges || []
    }))
  },
  orgs: {
    base: orgs.base,
    orgs: (orgs.orgs || []).map(o => ({ name: o.name, uri: o.uri, cats: o.cats || [], members: o.members || 0, meets: o.meets || '', desc: (o.desc || '').slice(0, 220), upcoming: o.upcoming || 0 }))
  },
  news: { generatedAt: news.generatedAt, colleges: news.colleges || {} }
};

const out = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../data.js');
fs.writeFileSync(out, '/* Generated by scripts/build-data.mjs from publicly published Georgia Southern sources. Do not edit by hand. */\nwindow.ROAM_DATA=' + JSON.stringify(bundle) + ';\n');
console.log(`data.js written: ${bundle.events.events.length} events, ${bundle.orgs.orgs.length} orgs, ${academics.majors.length} majors, ${campus.places.length} places`);
